static void clock_render(int full) {
    char digits[12]="--:--";
    char date[64]="--.--.----";
    static const char *wd[]={"ВОСКРЕСЕНЬЕ","ПОНЕДЕЛЬНИК","ВТОРНИК","СРЕДА",
                            "ЧЕТВЕРГ","ПЯТНИЦА","СУББОТА"};
    time_t now=time(NULL); struct tm *t=localtime(&now);
    int c=col(),r=hor();
    if(t) {
        strftime(digits,sizeof(digits),"%H:%M",t);
        snprintf(date,sizeof(date),"%s  %02d.%02d.%04d",wd[t->tm_wday],
                 t->tm_mday,t->tm_mon+1,t->tm_year+1900);
        last_minute=t->tm_min;
    }
    FillArea(15,16,c-32,r-29,WHITE);
    number(digits,22,24,101,231,8);
    if(f_date) { SetFont(f_date,BLACK); DrawString(30,r-89,date); }
    if(full) FullUpdate();
    else PartialUpdate(15,16,c-32,r-29);
}
static void tick(void) {
    time_t now=time(NULL); struct tm *t=localtime(&now);
    if(!t || t->tm_min!=last_minute) clock_render((++refresh_count%12)==0);
    SetHardTimer("burbuli05_tick",tick,30000);
}
static void auto_exit(void) { CloseApp(); }
static int handler(int type,int p1,int p2) {
    (void)p2;
    switch(type) {
      case EVT_INIT:
        SetOrientation(1);
        f_date=OpenFont("LiberationSans-Bold",42,0);
        f_small=OpenFont("LiberationSans",23,0);
        f_unit=OpenFont("LiberationSans-Bold",55,0);
        f_hum=OpenFont("LiberationSans-Bold",49,0);
        SetHardTimer("burbuli05_tick",tick,30000);
        SetHardTimer("burbuli05_exit",auto_exit,900000);
        return 1;
      case EVT_SHOW:
      case EVT_REPAINT:
      case EVT_ORIENTATION:
        static_page(); clock_render(1); return 1;
      case EVT_KEYDOWN:
        if(p1==IV_KEY_PREV) {
          time_t now=time(NULL);
          if(exit_count==0 || now-exit_window>5) {exit_window=now;exit_count=1;}
          else exit_count++;
          if(exit_count>=5) CloseApp();
        }
        return 1;
      case EVT_KEYUP:
      case EVT_KEYREPEAT: return 1;
      case EVT_EXIT:
        ClearTimerByName("burbuli05_tick");
        ClearTimerByName("burbuli05_exit");
        if(f_date) CloseFont(f_date);
        if(f_small) CloseFont(f_small);
        if(f_unit) CloseFont(f_unit);
        if(f_hum) CloseFont(f_hum);
        return 1;
      default: return 0;
    }
}
int main(int argc,char **argv) {
    (void)argc;(void)argv;
    InkViewMain(handler);
    return 0;
}
