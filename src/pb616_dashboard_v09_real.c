static void network_poll(void) {
    DISPLAY_DATA next;
    memset(&next,0,sizeof(next));
    read_home(&next);
    read_aranet(&next);
    /* Redraw only when something has changed. No stale cached data. */
    if(memcmp(&next,&live_data,sizeof(next))!=0) {
        live_data=next;
        draw_measurements();
        PartialUpdate(25,12,711,997);
    }
    SetHardTimer("burbuli_v09_net",network_poll,120000);
}
static void clock_render(int full) {
    char time_text[12]="--:--";
    char date_text[30]="--.--.----";
    static const char *weekday[]={
       "ВОСКРЕСЕНЬЕ","ПОНЕДЕЛЬНИК","ВТОРНИК","СРЕДА",
       "ЧЕТВЕРГ","ПЯТНИЦА","СУББОТА"
    };
    time_t now=time(NULL); struct tm *tm=localtime(&now);
    if(tm) {
        strftime(time_text,sizeof(time_text),"%H:%M",tm);
        snprintf(date_text,sizeof(date_text),"%02d.%02d.%04d",
                 tm->tm_mday,tm->tm_mon+1,tm->tm_year+1900);
        last_minute=tm->tm_min;
        last_day=tm->tm_yday;
    }
    /* clock portion only; measurements are refreshed independently */
    FillArea(28,120,701,443,WHITE);
    number(time_text,57,130,139,321,7);
    if(f_date && f_day) {
        SetFont((tm && strlen(weekday[tm->tm_wday])>17)?f_longday:f_day,BLACK);
        DrawString(38,498,tm?weekday[tm->tm_wday]:"ДЕНЬ");
        DrawLine(389,499,389,561,BLACK);
        SetFont(f_date,BLACK);
        DrawString(412,500,date_text);
    }
    if(full) FullUpdate();
    else PartialUpdate(28,120,701,443);
}
static void tick(void) {
    time_t now=time(NULL); struct tm *tm=localtime(&now);
    if(!tm || tm->tm_min!=last_minute || tm->tm_yday!=last_day)
        clock_render((++refresh_count%12)==0);
    SetHardTimer("burbuli_v09_tick",tick,30000);
}
static int handler(int type,int p1,int p2) {
    (void)p2;
    switch(type) {
      case EVT_INIT:
        SetOrientation(0); /* portrait; PocketBook physical buttons BELOW */
        f_day=OpenFont("LiberationSans-Bold",43,0);
        f_longday=OpenFont("LiberationSans-Bold",36,0);
        f_date=OpenFont("LiberationSans-Bold",44,0);
        f_unit=OpenFont("LiberationSans-Bold",47,0);
        f_humidity=OpenFont("LiberationSans-Bold",44,0);
        f_small=OpenFont("LiberationSans",21,0);
        f_soc=OpenFont("LiberationSans-Bold",52,0);
        SetHardTimer("burbuli_v09_tick",tick,30000);
        return 1;
      case EVT_SHOW:
      case EVT_REPAINT:
      case EVT_ORIENTATION:
        draw_page(); clock_render(1);
        if(!network_timer_started) {
            network_timer_started=1;
            SetHardTimer("burbuli_v09_net",network_poll,2000);
        }
        return 1;
      case EVT_KEYDOWN:
        if(p1==IV_KEY_PREV) {
            time_t now=time(NULL);
            if(exit_count==0 || now-exit_window>5) {
                exit_window=now; exit_count=1;
            } else exit_count++;
            if(exit_count>=5) CloseApp();
        }
        return 1;
      case EVT_KEYUP:
      case EVT_KEYREPEAT: return 1;
      case EVT_EXIT:
        ClearTimerByName("burbuli_v09_tick");
        ClearTimerByName("burbuli_v09_net");
        if(f_day) CloseFont(f_day);
        if(f_longday) CloseFont(f_longday);
        if(f_date) CloseFont(f_date);
        if(f_unit) CloseFont(f_unit);
        if(f_humidity) CloseFont(f_humidity);
        if(f_small) CloseFont(f_small);
        if(f_soc) CloseFont(f_soc);
        return 1;
      default: return 0;
    }
}
int main(int argc,char **argv) {
    (void)argc; (void)argv;
    InkViewMain(handler);
    return 0;
}
