/* High-contrast glyphs: independently selectable W and H, no system font or assets. */
static void glyph(char c,int x,int y,int width,int height) {
    int idx=(c=='.')?10:((c>='0' && c<='9')?c-'0':-1);
    if(idx<0) return;
    const GLYPH *g=&glyphs[idx];
    int j;
    for(j=0;j<g->n;j++) {
        const GLYPHRECT *r=&g->rects[j];
        int x0=x+(r->x0*width)/60;
        int x1=x+(r->x1*width+59)/60;
        int y0=y+(r->y0*height)/112;
        int y1=y+(r->y1*height+111)/112;
        if(x1>x0 && y1>y0) FillArea(x0,y0,x1-x0,y1-y0,BLACK);
    }
}
static int number(const char *s,int x,int y,int dw,int dh,int gap) {
    while(*s) {
        if(*s==':') {
            int cw=dw/4, sz=cw;
            FillArea(x+1,y+dh/3,sz,sz,BLACK);
            FillArea(x+1,y+(dh*2)/3,sz,sz,BLACK);
            x+=cw+gap;
        } else if(*s=='.') {
            int dot=dw/4;
            glyph('.',x,y,dot,dh);
            x+=dot+gap/2;
        } else if(*s>='0' && *s<='9') {
            glyph(*s,x,y,dw,dh);
            x+=dw+gap;
        } else if(*s=='-') {
            FillArea(x,y+dh/2-6,dw/2,12,BLACK);
            x+=dw/2+gap;
        } else if(*s==' ') x+=dw/4;
        ++s;
    }
    return x;
}

/* SOC comes ONLY from the Pi calc_soc field, not the invalid
 * EPEver battery_soc. Six segments, rounded to nearest filled block. */
static void round_fill(int x,int y,int w,int h,int radius,int colour) {
    int row;
    for(row=0;row<h;row++) {
        int cap=row,cut=0;
        if(h-1-row<cap) cap=h-1-row;
        if(cap<radius) {
            int yy=radius-1-cap,xx;
            for(xx=radius;xx>=0;xx--) if(xx*xx+yy*yy<=radius*radius) break;
            cut=radius-xx;
        }
        if(w-2*cut>0) FillArea(x+cut,y+row,w-2*cut,1,colour);
    }
}
