static void draw_icon(const ICON *icon,int x,int y) {
    int iy,ix;
    for(iy=0;iy<icon->h;iy++) {
        int start=-1;
        for(ix=0;ix<=icon->w;ix++) {
            int black=0;
            if(ix<icon->w) {
                int pos=iy*icon->w+ix;
                black=(icon->pixels[pos>>3]>>(7-(pos&7)))&1;
            }
            if(black && start<0) start=ix;
            if(!black && start>=0) {
                FillArea(x+start,y+iy,ix-start,1,BLACK);
                start=-1;
            }
        }
    }
}
